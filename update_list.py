def load_existing_ids(root):
    existing_ids = set()
    for anime in root.findall('anime'):
        db_id = anime.find('series_animedb_id')
        if db_id is not None and db_id.text:
            existing_ids.add(int(db_id.text))
    return existing_ids

def add_anime_node(root, title, mal_id, status):
    anime_node = ET.SubElement(root, 'anime')
    
    id_node = ET.SubElement(anime_node, 'series_animedb_id')
    id_node.text = str(mal_id)
    
    title_node = ET.SubElement(anime_node, 'series_title')
    title_node.text = title
    
    score_node = ET.SubElement(anime_node, 'my_score')
    score_node.text = '0'
    
    status_node = ET.SubElement(anime_node, 'my_status')
    status_node.text = 'Completed' if status == 'c' else 'Watching'
    
    ep_node = ET.SubElement(anime_node, 'my_watched_episodes')
    ep_node.text = '0' if status == 'c' else '1'
    
    import_node = ET.SubElement(anime_node, 'update_on_import')
    import_node.text = '1'

def main():
    if not os.path.exists(XML_PATH):
        print(f"Erreur : Le fichier {XML_PATH} est introuvable.")
        return

    parser = ET.XMLParser(encoding="utf-8")
    tree = ET.parse(XML_PATH, parser=parser)
    root = tree.getroot()
    
    existing_ids = load_existing_ids(root)
    added_count = 0
    
    print("=== ASSISTANT DE SUGGESTION MASSIF (500 ANIMES) ===")
    print("Entrez 'c' (Complété), 'e' (En cours), 'p' (Passer), 'q' (Quitter et sauvegarder)\n")
    
    for title, mal_id in SUGGESTIONS:
        if mal_id in existing_ids:
            continue
            
        response = input(f"Avez-vous vu '{title}' ? [c/e/p/q] : ").strip().lower()
        
        if response == 'q':
            print("Sauvegarde en cours...")
            break
        elif response in ['c', 'e']:
            add_anime_node(root, title, mal_id, response)
            existing_ids.add(mal_id)
            added_count += 1
            print(f"-> Ajouté : {title} ({'Vu' if response == 'c' else 'En cours'})")
        elif response == 'p':
            continue
        else:
            print("Entrée invalide, choix sauté.")
            
    if added_count > 0:
        # Save changes back to XML
        tree.write(XML_PATH, encoding='utf-8', xml_declaration=True)
        print(f"\nSauvegardé avec succès ! {added_count} animés ajoutés à {XML_PATH}.")
    else:
        print("\nAucun changement.")

if __name__ == '__main__':
    main()
